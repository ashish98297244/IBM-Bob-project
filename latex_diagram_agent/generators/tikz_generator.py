def detect_diagram_type(description: str) -> Optional[str]:
    """
    Heuristically detect the diagram type from the description text.

    Parameters
    ----------
    description : str
        Plain-English diagram description.

    Returns
    -------
    str or None
        The detected category string, or None if ambiguous.
    """
    desc_lower = description.lower()
    scores: dict[str, int] = {}

    for diagram_type, keywords in _TYPE_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in desc_lower)
        if score:
            scores[diagram_type] = score

    if not scores:
        return None

    return max(scores, key=lambda t: scores[t])


# ---------------------------------------------------------------------------
# Post-processing / cleaning of generated code
# ---------------------------------------------------------------------------

# Packages that should always be present in a TikZ document
_ESSENTIAL_PACKAGES = [
    "\\usepackage{tikz}",
]

_DOCUMENTCLASS_RE = re.compile(r"\\documentclass(\[.*?\])?\{.*?\}", re.DOTALL)
_BEGIN_DOC_RE = re.compile(r"\\begin\{document\}")
_END_DOC_RE = re.compile(r"\\end\{document\}")
_USEPACKAGE_RE = re.compile(r"\\usepackage(\[.*?\])?\{.*?\}")


def ensure_compilable(tikz_code: str) -> str:
    """
    Ensure the TikZ code is wrapped in a compilable LaTeX document.

    If Granite returned a bare TikZ picture (without \\documentclass),
    this wraps it in a minimal standalone document.

    Parameters
    ----------
    tikz_code : str
        Raw code from the model.

    Returns
    -------
    str
        Compilable LaTeX document string.
    """
    if _DOCUMENTCLASS_RE.search(tikz_code) and _BEGIN_DOC_RE.search(tikz_code):
        return tikz_code  # already a full document

    # Build a minimal standalone wrapper
    return (
        "\\documentclass[tikz,border=4mm]{standalone}\n"
        "\\usepackage{tikz}\n"
        "\\usetikzlibrary{shapes.geometric,arrows.meta,positioning,"
        "automata,trees,backgrounds,fit,calc}\n"
        "\\begin{document}\n"
        "\\begin{tikzpicture}\n"
        f"{tikz_code.strip()}\n"
        "\\end{tikzpicture}\n"
        "\\end{document}\n"
    )


def strip_markdown_fences(text: str) -> str:
    """Remove surrounding ```latex ... ``` fences if present."""
    stripped = re.sub(r"^```(?:latex|tex)?\s*\n", "", text.strip(), flags=re.IGNORECASE)
    stripped = re.sub(r"\n```\s*$", "", stripped)
    return stripped.strip()


def add_header_comment(tikz_code: str, description: str) -> str:
    """
    Prepend a descriptive comment header to the LaTeX file.
    """
    header = (
        "% ============================================================\n"
        "% Generated by AI-Powered LaTeX Diagram Generator\n"
        "% IBM Watson Studio + IBM Granite Models\n"
        f"% Description: {description[:120]}\n"
        "% ============================================================\n"
    )
    return header + tikz_code


def post_process(tikz_code: str, description: str = "") -> str:
    """
    Full post-processing pipeline:
      1. Strip markdown fences
      2. Ensure compilable document structure
      3. Prepend header comment

    Parameters
    ----------
    tikz_code : str
        Raw code from the model (possibly fenced).
    description : str, optional
        Original description for the header comment.

    Returns
    -------
    str
        Clean, compilable LaTeX document.
    """
    code = strip_markdown_fences(tikz_code)
    code = ensure_compilable(code)
    if description:
        code = add_header_comment(code, description)
    return code


